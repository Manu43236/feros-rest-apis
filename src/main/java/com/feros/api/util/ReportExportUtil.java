package com.feros.api.util;

import com.lowagie.text.*;
import com.lowagie.text.pdf.*;
import com.opencsv.CSVWriter;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.OutputStreamWriter;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

public class ReportExportUtil {

    private ReportExportUtil() {}

    private static final DateTimeFormatter GEN_FMT = DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a");

    // Paints the document header (tenant + report title) and footer on EVERY page,
    // so page 2+ are no longer missing the header. Fired by OpenPDF per page.
    private static class HeaderFooterEvent extends PdfPageEventHelper {
        private final String tenantName;
        private final String title;
        private final String generatedAt;

        HeaderFooterEvent(String tenantName, String title) {
            this.tenantName = tenantName;
            this.title = title;
            this.generatedAt = "Generated by FEROS  ·  " + LocalDateTime.now().format(GEN_FMT);
        }

        @Override
        public void onEndPage(PdfWriter writer, Document doc) {
            PdfContentByte cb = writer.getDirectContent();
            float left = doc.left();
            float right = doc.right();
            float headerTop = doc.top() + 30f;

            if (tenantName != null && !tenantName.isBlank()) {
                Font tenantFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 13, Color.decode("#0F172A"));
                ColumnText.showTextAligned(cb, Element.ALIGN_LEFT, new Phrase(tenantName, tenantFont), left, headerTop, 0);
            }
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 11, Color.decode("#1E3A5F"));
            ColumnText.showTextAligned(cb, Element.ALIGN_LEFT, new Phrase(title, titleFont), left, headerTop - 15f, 0);

            cb.setColorStroke(Color.decode("#E2E8F0"));
            cb.setLineWidth(0.5f);
            cb.moveTo(left, headerTop - 22f);
            cb.lineTo(right, headerTop - 22f);
            cb.stroke();

            Font footerFont = FontFactory.getFont(FontFactory.HELVETICA, 7, Color.GRAY);
            float footerY = doc.bottom() - 18f;
            ColumnText.showTextAligned(cb, Element.ALIGN_LEFT,
                    new Phrase("Page " + writer.getPageNumber(), footerFont), left, footerY, 0);
            ColumnText.showTextAligned(cb, Element.ALIGN_RIGHT,
                    new Phrase(generatedAt, footerFont), right, footerY, 0);
        }
    }

    // Prepend a leading "S.No" serial column to every export so each report row is numbered.
    private static final String SERIAL_HEADER = "S.No";

    private static String[] withSerialHeader(String[] headers) {
        String[] out = new String[headers.length + 1];
        out[0] = SERIAL_HEADER;
        System.arraycopy(headers, 0, out, 1, headers.length);
        return out;
    }

    private static String[] withSerialCell(String[] row, int serial) {
        String[] out = new String[row.length + 1];
        out[0] = String.valueOf(serial);
        System.arraycopy(row, 0, out, 1, row.length);
        return out;
    }

    public static byte[] toCsv(String[] headers, List<String[]> rows) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream();
             CSVWriter writer = new CSVWriter(new OutputStreamWriter(out, StandardCharsets.UTF_8))) {
            writer.writeNext(withSerialHeader(headers));
            for (int i = 0; i < rows.size(); i++) {
                writer.writeNext(withSerialCell(rows.get(i), i + 1));
            }
            writer.flush();
            return out.toByteArray();
        } catch (Exception e) {
            throw new RuntimeException("Failed to generate CSV", e);
        }
    }

    public static byte[] toPdf(String tenantName, String title, String[] headers, List<String[]> rows) {
        return toPdf(tenantName, title, null, headers, rows);
    }

    // summaryLines: e.g. [["Total Vehicles", "42"], ["Available", "10"], ...]
    public static byte[] toPdf(String tenantName, String title, List<String[]> summaryLines, String[] headers, List<String[]> rows) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            // top/bottom margins widened to make room for the per-page header/footer band
            Document doc = new Document(PageSize.A4.rotate(), 30, 30, 72, 46);
            PdfWriter writer = PdfWriter.getInstance(doc, out);
            writer.setPageEvent(new HeaderFooterEvent(tenantName, title));
            doc.open();

            // ── Watermark ────────────────────────────────────────────────────
            PdfContentByte canvas = writer.getDirectContentUnder();
            Font wmFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 72);
            wmFont.setColor(230, 230, 230);
            PdfGState gs = new PdfGState();
            gs.setFillOpacity(0.15f);
            canvas.saveState();
            canvas.setGState(gs);
            canvas.beginText();
            canvas.setFontAndSize(wmFont.getBaseFont(), 72);
            canvas.showTextAligned(Element.ALIGN_CENTER, "FEROS",
                    doc.getPageSize().getWidth() / 2,
                    doc.getPageSize().getHeight() / 2,
                    45);
            canvas.endText();
            canvas.restoreState();

            // Tenant name + title are now painted on every page by HeaderFooterEvent.

            // ── Summary block ─────────────────────────────────────────────────
            if (summaryLines != null && !summaryLines.isEmpty()) {
                PdfPTable summary = new PdfPTable(summaryLines.size());
                summary.setWidthPercentage(100f);
                summary.setSpacingAfter(10f);
                Font labelFont = FontFactory.getFont(FontFactory.HELVETICA, 7.5f, Color.GRAY);
                Font valueFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 13f, Color.decode("#1E3A5F"));
                for (String[] kv : summaryLines) {
                    PdfPCell cell = new PdfPCell();
                    cell.setBorderColor(Color.decode("#E2E8F0"));
                    cell.setPadding(8f);
                    cell.setBackgroundColor(Color.decode("#F8FAFC"));
                    cell.addElement(new Phrase(kv[0], labelFont));
                    cell.addElement(new Phrase(kv[1], valueFont));
                    summary.addCell(cell);
                }
                doc.add(summary);
            }

            // ── Table ─────────────────────────────────────────────────────────
            // +1 column for the leading "S.No" serial index.
            String[] serialHeaders = withSerialHeader(headers);
            PdfPTable table = new PdfPTable(serialHeaders.length);
            table.setWidthPercentage(100f);
            table.setSpacingBefore(6f);
            table.setHeaderRows(1); // repeat the header row on every page

            Font headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 8, Color.WHITE);
            Color headerBg = Color.decode("#1E3A5F");
            for (String h : serialHeaders) {
                PdfPCell cell = new PdfPCell(new Phrase(h, headerFont));
                cell.setBackgroundColor(headerBg);
                cell.setPadding(5f);
                cell.setHorizontalAlignment(Element.ALIGN_CENTER);
                table.addCell(cell);
            }

            Font dataFont = FontFactory.getFont(FontFactory.HELVETICA, 7.5f, Color.DARK_GRAY);
            Color altBg = Color.decode("#F1F5F9");
            for (int i = 0; i < rows.size(); i++) {
                Color rowBg = (i % 2 == 0) ? Color.WHITE : altBg;
                for (String val : withSerialCell(rows.get(i), i + 1)) {
                    PdfPCell cell = new PdfPCell(new Phrase(val == null ? "" : val, dataFont));
                    cell.setBackgroundColor(rowBg);
                    cell.setPadding(4f);
                    table.addCell(cell);
                }
            }

            doc.add(table);

            // Footer is painted on every page by HeaderFooterEvent.
            doc.close();
            return out.toByteArray();
        } catch (Exception e) {
            throw new RuntimeException("Failed to generate PDF", e);
        }
    }

    public static ResponseEntity<byte[]> csvResponse(String filename, byte[] data) {
        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"" + filename + ".csv\"")
                .contentType(MediaType.parseMediaType("text/csv"))
                .body(data);
    }

    public static ResponseEntity<byte[]> pdfResponse(String filename, byte[] data) {
        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"" + filename + ".pdf\"")
                .contentType(MediaType.APPLICATION_PDF)
                .body(data);
    }
}
